// Regenerates the temples block of supabase/seed.sql (then appends supabase/seed/static.sql) from packages/core/src/mock/temple.ts so the SQL seed
// and the mock TEMPLES never drift.   node supabase/scripts/gen-seed-temples.mjs
// (Node >= 22.6 strips TS types natively.)
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

const { TEMPLES } = await import(pathToFileURL(resolve('packages/core/src/mock/temple.ts')).href)

const q = (s) => `'${String(s).replaceAll("'", "''")}'`
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`
const uuid = (i) => `00000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`

const rows = TEMPLES.map((t, i) => `  (${[
  q(uuid(i)), q(t.id), q(t.slug), q(t.name), q(t.address), q(t.city), q(t.state), q(t.zip), q(t.country),
  q(t.phone), q(t.email), q(t.timezone), q(JSON.stringify(t.timings)) + '::jsonb', q(t.logoUrl), arr(t.deities),
  q(t.currency), q(t.locale), arr(t.languages), q(t.taxRegime), q(t.taxId), q(t.taxIdLabel), t.lat, t.lng,
  q(t.about), q(JSON.stringify(t.spaces)) + '::jsonb', arr(t.payments), arr(t.shipsTo), q(t.status), t.isDemo,
].join(', ')})`)

const sql = `-- GENERATED by supabase/scripts/gen-seed-temples.mjs from packages/core/src/mock/temple.ts. Do not edit.
insert into public.temples
  (id, legacy_id, slug, name, address, city, state, zip, country, phone, email, timezone, timings, logo_url, deities,
   currency, locale, languages, tax_regime, tax_id, tax_id_label, lat, lng, about, spaces, payments, ships_to, status, is_demo)
values
${rows.join(',\n')}
on conflict (slug) do nothing;
`
writeFileSync('supabase/seed.sql', sql + readFileSync('supabase/seed/static.sql','utf8'))
console.log('wrote supabase/seed.sql with', TEMPLES.length, 'temples')
